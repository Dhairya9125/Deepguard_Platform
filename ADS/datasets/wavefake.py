"""WaveFake dataset loader.

WaveFake contains audio generated by various GAN and diffusion
vocoders: WaveGlow, MelGAN, HiFi-GAN, WaveGAN, Diffusion.
"""

from __future__ import annotations

import logging
from pathlib import Path

from datasets.base import AudioDeepfakeDataset, AudioSample

logger = logging.getLogger(__name__)


class WaveFakeDataset(AudioDeepfakeDataset):
    """WaveFake dataset loader.

    Directory structure:
        WaveFake/
            real/
                speaker_01/
                    *.wav
                ...
            fake/
                waveglow/
                    speaker_01/
                        *.wav
                melgan/
                hifigan/
                ...
    """

    KNOWN_VOCODERS = [
        "waveglow",
        "melgan",
        "hifigan",
        "wavegan",
        "diffusion",
        "parallel_wavegan",
        "multiband_melgan",
        "full_band_melgan",
    ]

    def _load_filelist(self) -> None:
        root = Path(self.root_dir)

        real_dir = root / "real"
        if real_dir.exists():
            self._add_real_files(real_dir)

        fake_dir = root / "fake"
        if fake_dir.exists():
            self._add_fake_files(fake_dir)

        if not self.samples:
            logger.info("Scanning flat directory structure")
            self._scan_flat(root)

    def _add_real_files(self, real_dir: Path) -> None:
        for speaker_dir in sorted(real_dir.iterdir()):
            if speaker_dir.is_dir():
                for fpath in sorted(speaker_dir.glob("*.wav")):
                    self.samples.append(
                        AudioSample(
                            audio_path=str(fpath),
                            label=0,
                            sample_id=fpath.stem,
                            speaker_id=speaker_dir.name,
                            dataset_name="WaveFake",
                            manipulation_type="bonafide",
                        )
                    )

    def _add_fake_files(self, fake_dir: Path) -> None:
        for vocoder_dir in sorted(fake_dir.iterdir()):
            if vocoder_dir.is_dir():
                for speaker_dir in sorted(vocoder_dir.iterdir()):
                    if speaker_dir.is_dir():
                        for fpath in sorted(speaker_dir.glob("*.wav")):
                            self.samples.append(
                                AudioSample(
                                    audio_path=str(fpath),
                                    label=1,
                                    sample_id=fpath.stem,
                                    speaker_id=speaker_dir.name,
                                    dataset_name="WaveFake",
                                    manipulation_type=vocoder_dir.name,
                                )
                            )

    def _scan_flat(self, root: Path) -> None:
        for subset_dir in ["train", "dev", "eval"]:
            path = root / subset_dir
            if not path.exists():
                continue
            for fpath in sorted(path.glob("**/*.wav")):
                parent = fpath.parent.name
                is_fake = any(v in str(fpath) for v in self.KNOWN_VOCODERS)
                self.samples.append(
                    AudioSample(
                        audio_path=str(fpath),
                        label=1 if is_fake else 0,
                        sample_id=fpath.stem,
                        speaker_id=parent,
                        dataset_name="WaveFake",
                        manipulation_type="fake" if is_fake else "bonafide",
                    )
                )
